package com.gntcyouthbe.acceptance.steps;

import static org.assertj.core.api.Assertions.assertThat;

import com.gntcyouthbe.acceptance.support.api.ThanksApi;
import com.gntcyouthbe.acceptance.support.context.ThanksScenarioContext;
import com.gntcyouthbe.acceptance.support.context.World;
import io.cucumber.datatable.DataTable;
import io.cucumber.java.After;
import io.cucumber.java.Before;
import io.cucumber.java.ko.그러면;
import io.cucumber.java.ko.만일;
import io.cucumber.java.ko.먼저;
import io.restassured.response.ExtractableResponse;
import io.restassured.response.Response;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;

public class ThanksCellStepDefs {

    private static final Long UNKNOWN_CELL_ID = 999_999L;

    private final World world;
    private final ThanksScenarioContext thanks;
    private final ThanksApi thanksApi;
    private final JdbcTemplate jdbcTemplate;

    private final List<Integer> concurrentStatusCodes = new ArrayList<>();

    public ThanksCellStepDefs(World world, ThanksScenarioContext thanks, ThanksApi thanksApi, JdbcTemplate jdbcTemplate) {
        this.world = world;
        this.thanks = thanks;
        this.thanksApi = thanksApi;
        this.jdbcTemplate = jdbcTemplate;
    }

    @Before("@thanks-cell")
    public void 구역을_비운다() {
        jdbcTemplate.update("DELETE FROM thanks_cell_member");
        jdbcTemplate.update("DELETE FROM thanks_cell");
    }

    // 예전 테이블은 엔티티가 없어서 create-drop이 지워 주지 않는다
    @After("@thanks-cell")
    public void 예전_구역_테이블을_지운다() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS cell_member");
    }

    // --- 준비 ---

    // 관리 화면이 없어서 운영에서도 구역은 이 모양의 SQL로 직접 넣는다
    @먼저("구역이 다음과 같이 있다")
    public void 구역이_있다(DataTable cells) {
        for (Map<String, String> cell : cells.asMaps()) {
            String name = cell.get("이름");
            jdbcTemplate.update("INSERT INTO thanks_cell (name, sort_order) VALUES (?, ?)",
                    name, Integer.parseInt(cell.get("순서")));
            thanks.saveCellId(name, jdbcTemplate.queryForObject("SELECT id FROM thanks_cell WHERE name = ?", Long.class, name));
        }
    }

    @먼저("{string}가 구역 {string}을/를 골랐다")
    public void 구역을_골랐다(String userName, String cellName) {
        구역을_고른다(userName, cellName);
        assertThat(world.response.statusCode()).isEqualTo(HttpStatus.OK.value());
    }

    // 2025년 성경 필사 때의 테이블이 운영 DB에 남아 있는 경우. 새 구역과 같은 id로 넣어 둔다.
    @먼저("{string}가 예전 성경 필사 구역에 들어 있다")
    public void 예전_구역에_들어_있다(String userName) {
        jdbcTemplate.execute("CREATE TABLE cell_member (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cell_id BIGINT NOT NULL, user_id BIGINT NOT NULL)");
        jdbcTemplate.update("INSERT INTO cell_member (cell_id, user_id) VALUES (?, ?)",
                thanks.cellIdOf("할렐루야구역"), thanks.userIdOf(userName));
    }

    // --- 요청 ---

    @만일("{string}가 구역 목록을 조회한다")
    public void 구역_목록을_조회한다(String userName) {
        world.response = thanksApi.getCells(thanks.tokenOf(userName));
    }

    @만일("로그인하지 않고 구역 목록을 조회한다")
    public void 로그인하지_않고_구역_목록을_조회한다() {
        world.response = thanksApi.getCellsWithoutAuth();
    }

    @만일("{string}가 구역 {string}을/를 고른다")
    public void 구역을_고른다(String userName, String cellName) {
        world.response = thanksApi.updateMyCell(thanks.tokenOf(userName), thanks.cellIdOf(cellName));
    }

    @만일("{string}가 없는 구역을 고른다")
    public void 없는_구역을_고른다(String userName) {
        world.response = thanksApi.updateMyCell(thanks.tokenOf(userName), UNKNOWN_CELL_ID);
    }

    @만일("{string}가 본문 {string}(으)로 구역을 고른다")
    public void 본문으로_구역을_고른다(String userName, String body) {
        world.response = thanksApi.updateMyCell(thanks.tokenOf(userName), body);
    }

    @만일("{string}가 본문 없이 구역을 고른다")
    public void 본문_없이_구역을_고른다(String userName) {
        world.response = thanksApi.updateMyCellWithoutBody(thanks.tokenOf(userName));
    }

    @만일("로그인하지 않고 구역 {string}을/를 고른다")
    public void 로그인하지_않고_구역을_고른다(String cellName) {
        world.response = thanksApi.updateMyCellWithoutAuth(thanks.cellIdOf(cellName));
    }

    // 요청을 한꺼번에 출발시켜서, 처음 고르는 요청끼리 행이 없는 것을 함께 보고 INSERT하는 경합을 만든다
    @만일("{string}가 구역 {string}을/를 동시에 {int}번 고른다")
    public void 구역을_동시에_고른다(String userName, String cellName, int times) {
        String token = thanks.tokenOf(userName);
        Long cellId = thanks.cellIdOf(cellName);
        ExecutorService executor = Executors.newFixedThreadPool(times);
        CountDownLatch start = new CountDownLatch(1);
        try {
            List<CompletableFuture<ExtractableResponse<Response>>> requests = new ArrayList<>();
            for (int i = 0; i < times; i++) {
                requests.add(CompletableFuture.supplyAsync(() -> {
                    awaitQuietly(start);
                    return thanksApi.updateMyCell(token, cellId);
                }, executor));
            }
            start.countDown();
            requests.forEach(request -> concurrentStatusCodes.add(request.join().statusCode()));
        } finally {
            executor.shutdownNow();
        }
    }

    // --- 확인 ---

    @그러면("응답한 구역은 차례대로 {string}이다")
    public void 응답한_구역은_차례대로다(String names) {
        assertThat(world.response.jsonPath().getList("cells.name", String.class))
                .containsExactlyElementsOf(Arrays.asList(names.split(", ")));
    }

    @그러면("응답한 내 구역은 없다")
    public void 응답한_내_구역은_없다() {
        Map<String, Object> body = world.response.jsonPath().getMap("$");
        assertThat(body).containsEntry("myCellId", null);
    }

    @그러면("응답한 내 구역은 {string}이다")
    public void 응답한_내_구역은_이다(String cellName) {
        assertThat(world.response.jsonPath().getLong("myCellId")).isEqualTo(thanks.cellIdOf(cellName));
    }

    @그러면("응답의 키는 정확히 {string}이고 구역 키는 정확히 {string}이다")
    public void 응답의_키는_정확히_이다(String responseKeys, String cellKeys) {
        Map<String, Object> body = world.response.jsonPath().getMap("$");
        assertThat(body.keySet()).containsExactlyInAnyOrder(responseKeys.split(", "));
        Map<String, Object> cell = world.response.jsonPath().getMap("cells[0]");
        assertThat(cell.keySet()).containsExactlyInAnyOrder(cellKeys.split(", "));
    }

    @그러면("동시에 보낸 요청은 모두 200이다")
    public void 동시에_보낸_요청은_모두_200이다() {
        assertThat(concurrentStatusCodes).isNotEmpty().containsOnly(HttpStatus.OK.value());
    }

    @그러면("{string}의 구역 행은 {int}개이다")
    public void 구역_행은_개수만큼이다(String userName, int count) {
        Long rows = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM thanks_cell_member WHERE user_id = ?",
                Long.class, thanks.userIdOf(userName));
        assertThat(rows).isEqualTo(count);
    }

    private void awaitQuietly(CountDownLatch latch) {
        try {
            latch.await();
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException(e);
        }
    }
}
